#include "gw_sens.h"


void gw_delay(uint32_t delay_count)
{
	for (int i = 0; i < delay_count; ++i) {
		__NOP();
	}
}

uint8_t gw_gray_serial_read(void)
{
	uint8_t ret = 0;

	for (int i = 0; i < 8; ++i) {
		/* ??????????? */
		DL_GPIO_clearPins(GW_SENSOR_PORT, GW_SENSOR_PIN_1_PIN);
		gw_delay(GW_GRAY_SERIAL_DELAY_VALUE); // ?????????(???10k????) ????????
		ret |= DL_GPIO_readPins(GW_SENSOR_PORT, GW_SENSOR_PIN_0_PIN) << i;

		DL_GPIO_setPins(GW_SENSOR_PORT, GW_SENSOR_PIN_1_PIN);

		/* ?????????????????????,????????5us???? */
		gw_delay(GW_GRAY_SERIAL_DELAY_VALUE);
	}

	return ret;
}